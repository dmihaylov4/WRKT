//  Past workouts sheet (Cut Train tab): the recent logged workouts that can be started again,
//  the plain values the sheet shows for each, and the entries a repeat starts with.
//  Nothing here reads a service; CutTrainHost feeds it the store's history and an
//  exercise lookup, and tests and captures feed it fixtures.
