import Foundation

/// One exercise row: the name on the left, last time's sets on the right.
struct CutPastWorkoutExercise: Equatable, Identifiable {
    let id: UUID
    let name: String
    /// "3 × 8, 100 kg", "4 sets, top 100 kg × 6", "3 × 12", "3 sets, 0:30-1:00".
    let summary: String
    /// The row as one VoiceOver phrase: "Bench Press, 3 sets of 8 reps, 100 kg".
    let accessibilityLabel: String
}

/// One workout page of the sheet.
struct CutPastWorkout: Equatable, Identifiable {
    let id: UUID
    let name: String
    /// The day as the Train tab's Last workout row says it: "Today", "Yesterday", "Sat", "Nov 3".
    let day: String
    let exercises: [CutPastWorkoutExercise]
}

/// Everything the past workouts sheet shows: newest first, at most three.
struct CutPastWorkoutsModel: Equatable {
    let workouts: [CutPastWorkout]
}

enum CutPastWorkoutsLogic {
    static let title = "Past workouts"
    static let startTitle = "Start this workout"
    static let olderLabel = "Older workout"
    static let newerLabel = "Newer workout"
    /// What the Train tab's Last workout row opens, for VoiceOver.
    static let rowHint = "Opens past workouts to start one again"
    static let maxCount = 3

    // MARK: Which workouts qualify

    /// The newest logged workouts that can be started again, newest first, at most three.
    /// `history` is oldest first, as WorkoutStoreV2 keeps `completedWorkouts` (it sorts by date
    /// on every change), so this walks back from the end and stops at the third match instead
    /// of sorting the whole history on every Train render.
    static func repeatable(
        _ history: [CompletedWorkout],
        isAvailable: (String) -> Bool = { _ in true }
    ) -> [CompletedWorkout] {
        var result: [CompletedWorkout] = []
        for workout in history.reversed() {
            if !entriesToRepeat(workout, isAvailable: isAvailable).isEmpty {
                result.append(workout)
                if result.count == maxCount { break }
            }
        }
        return result
    }

    // MARK: What gets pre-filled

    /// The sets of an entry that a repeat starts with. When the workout has completed sets
    /// (every workout logged since the app tracks completion), only those count: sets left
    /// unticked last time were not done. A workout with no completed set at all is older data
    /// that predates the flag, so its logged sets count. Untouched auto-added placeholders
    /// and sets with no value never count.
    static func setsToRepeat(_ entry: WorkoutEntry, workoutHasCompletedSets: Bool) -> [SetInput] {
        entry.sets.filter { set in
            guard !set.isAutoGeneratedPlaceholder, set.hasData else { return false }
            return workoutHasCompletedSets ? set.isCompleted : true
        }
    }

    static func hasCompletedSets(_ workout: CompletedWorkout) -> Bool {
        workout.entries.contains { $0.sets.contains(where: \.isCompleted) }
    }

    /// The entries a repeat of `workout` starts with, in their logged order: fresh ids, the
    /// sets as they were done (value, tag and tracking mode) but not yet logged, and editable.
    /// Exercises that are no longer in the library (`isAvailable` false, such as a deleted
    /// custom exercise) and exercises with no set to repeat are left out. Supersets keep their
    /// grouping under new group ids; a group left with one exercise is no longer a superset.
    static func entriesToRepeat(
        _ workout: CompletedWorkout,
        isAvailable: (String) -> Bool = { _ in true }
    ) -> [WorkoutEntry] {
        let completedOnly = hasCompletedSets(workout)
        var entries: [WorkoutEntry] = workout.entries.compactMap { entry in
            guard isAvailable(entry.exerciseID) else { return nil }
            let sets = setsToRepeat(entry, workoutHasCompletedSets: completedOnly).map(freshSet)
            guard !sets.isEmpty else { return nil }
            return WorkoutEntry(
                exerciseID: entry.exerciseID,
                exerciseName: entry.exerciseName,
                muscleGroups: entry.muscleGroups,
                sets: sets,
                supersetGroupID: entry.supersetGroupID,
                orderInSuperset: entry.orderInSuperset
            )
        }

        var memberCounts: [UUID: Int] = [:]
        for entry in entries {
            if let group = entry.supersetGroupID { memberCounts[group, default: 0] += 1 }
        }
        var newGroups: [UUID: UUID] = [:]
        for index in entries.indices {
            guard let group = entries[index].supersetGroupID else { continue }
            if memberCounts[group, default: 0] < 2 {
                entries[index].supersetGroupID = nil
                entries[index].orderInSuperset = nil
            } else {
                if newGroups[group] == nil { newGroups[group] = UUID() }
                entries[index].supersetGroupID = newGroups[group]
            }
        }
        return entries
    }

    /// The set as it was done, ready to log again: same as a planned workout's pre-filled set.
    static func freshSet(_ set: SetInput) -> SetInput {
        SetInput(
            reps: set.reps,
            weight: set.weight,
            tag: set.tag,
            autoWeight: false,
            isCompleted: false,
            isGhost: false,
            durationSeconds: set.durationSeconds,
            distanceMeters: set.distanceMeters,
            trackingMode: set.trackingMode
        )
    }

    // MARK: Sheet model

    static func model(
        _ workouts: [CompletedWorkout],
        unit: WeightUnit,
        isAvailable: (String) -> Bool = { _ in true },
        now: Date = .now,
        calendar: Calendar = .current
    ) -> CutPastWorkoutsModel {
        CutPastWorkoutsModel(workouts: workouts.prefix(maxCount).map { workout in
            CutPastWorkout(
                id: workout.id,
                name: CutTrainLogic.displayName(for: workout),
                day: CutTrainLogic.relativeDay(workout.date, now: now, calendar: calendar, style: .short),
                exercises: entriesToRepeat(workout, isAvailable: isAvailable).map { entry in
                    let summary = setSummary(entry.sets, unit: unit)
                    return CutPastWorkoutExercise(
                        id: entry.id,
                        name: entry.exerciseName,
                        summary: summary.text,
                        accessibilityLabel: "\(entry.exerciseName), \(summary.spoken)"
                    )
                }
            )
        })
    }

    // MARK: Set summary

    struct Summary: Equatable {
        let text: String
        let spoken: String
    }

    /// Last time's sets in a few words, in the user's unit. Warm-ups are pre-filled but left
    /// out of the summary when there are other sets, so it describes the work.
    ///   Weighted, all alike:   "3 × 8, 100 kg"           (3 sets of 8 reps, 100 kg)
    ///   Weighted, mixed:       "4 sets, top 100 kg × 6"  (the heaviest set, most reps on a tie)
    ///   Reps only, alike:      "3 × 12"
    ///   Reps only, mixed:      "3 sets, 10-12 reps"
    ///   Timed, alike:          "3 × 0:45"
    ///   Timed, mixed:          "3 sets, 0:30-1:00"
    ///   Distance, alike:       "2 × 400 m"
    ///   Distance, mixed:       "3 sets, 1.20 km total"
    ///   Mixed tracking modes:  "3 sets"
    static func setSummary(_ allSets: [SetInput], unit: WeightUnit) -> Summary {
        let work = allSets.filter { $0.tag != .warmup }
        let sets = work.isEmpty ? allSets : work
        let count = sets.count
        let setsWord = count == 1 ? "1 set" : "\(count) sets"
        guard let first = sets.first else { return Summary(text: "", spoken: "") }

        let modes = Set(sets.map { mode(of: $0) })
        guard modes.count == 1, let mode = modes.first else {
            return Summary(text: setsWord, spoken: setsWord)
        }

        switch mode {
        case .weighted:
            if sets.allSatisfy({ $0.reps == first.reps && $0.weight == first.weight }) {
                let weight = unit.format(first.weight)
                guard first.reps > 0 else { return Summary(text: "\(setsWord), \(weight)", spoken: "\(setsWord), \(weight)") }
                return Summary(text: "\(count) × \(first.reps), \(weight)",
                               spoken: "\(setsWord) of \(reps(first.reps)), \(weight)")
            }
            let top = sets.max { ($0.weight, $0.reps) < ($1.weight, $1.reps) } ?? first
            let weight = unit.format(top.weight)
            return Summary(text: "\(setsWord), top \(weight) × \(top.reps)",
                           spoken: "\(setsWord), top set \(weight) for \(reps(top.reps))")
        case .bodyweight:
            let values = sets.map(\.reps)
            let low = values.min() ?? 0, high = values.max() ?? 0
            if low == high {
                return Summary(text: "\(count) × \(low)", spoken: "\(setsWord) of \(reps(low))")
            }
            return Summary(text: "\(setsWord), \(low)-\(high) reps", spoken: "\(setsWord), \(low) to \(high) reps")
        case .timed:
            let values = sets.map(\.durationSeconds)
            let low = values.min() ?? 0, high = values.max() ?? 0
            if low == high {
                return Summary(text: "\(count) × \(duration(low))", spoken: "\(setsWord) of \(spokenDuration(low))")
            }
            return Summary(text: "\(setsWord), \(duration(low))-\(duration(high))",
                           spoken: "\(setsWord), \(spokenDuration(low)) to \(spokenDuration(high))")
        case .distance:
            if sets.allSatisfy({ $0.distanceMeters == first.distanceMeters }) {
                let value = distance(first.distanceMeters)
                return Summary(text: "\(count) × \(value)", spoken: "\(setsWord) of \(value)")
            }
            let total = distance(sets.reduce(0) { $0 + $1.distanceMeters })
            return Summary(text: "\(setsWord), \(total) total", spoken: "\(setsWord), \(total) total")
        }
    }

    /// A weighted set logged with no weight is a reps-only set.
    private static func mode(of set: SetInput) -> TrackingMode {
        set.trackingMode == .weighted && set.weight <= 0 ? .bodyweight : set.trackingMode
    }

    private static func reps(_ count: Int) -> String {
        count == 1 ? "1 rep" : "\(count) reps"
    }

    /// The set rows' durations: "0:45", "1:30", "1:02" (h:mm) from one hour.
    static func duration(_ seconds: Int) -> String {
        CutWorkoutDetailLogic.duration(seconds)
    }

    private static func spokenDuration(_ seconds: Int) -> String {
        Duration.seconds(max(0, seconds)).formatted(.units(allowed: [.hours, .minutes, .seconds], width: .wide))
    }

    /// The set rows' distances: "400 m", "2.50 km".
    static func distance(_ meters: Double) -> String {
        var set = SetInput(reps: 0, weight: 0)
        set.trackingMode = .distance
        set.distanceMeters = meters
        return CutWorkoutDetailLogic.setValue(set, unit: .kg)
    }

    /// The name as the sheet sets it: one line when short, else two balanced lines, so a long
    /// name wraps at a word before its glyphs shrink.
    static func nameLines(_ name: String) -> String {
        name.count > 11 ? CutHeroText.balancedLines(name) : name
    }

    // MARK: Paging

    /// Index 0 is the newest workout. Older moves to a higher index.
    static func canGoOlder(index: Int, count: Int) -> Bool { index + 1 < count }
    static func canGoNewer(index: Int, count: Int) -> Bool { index > 0 }

    /// The page step for a finished horizontal drag, or nil when the drag was mostly vertical
    /// or short (the sheet and the list keep those). A swipe to the left shows the newer
    /// workout, as the right arrow does; a swipe to the right shows the older one.
    static func swipeStep(dx: CGFloat, dy: CGFloat, threshold: CGFloat = 50) -> Int? {
        guard abs(dx) >= threshold, abs(dx) > abs(dy) * 1.5 else { return nil }
        return dx < 0 ? -1 : 1
    }

    /// The index after a step (+1 older, -1 newer), kept within the pages.
    static func stepped(_ index: Int, by step: Int, count: Int) -> Int {
        min(max(0, index + step), max(0, count - 1))
    }

    /// The sheet's height before it is measured: header, name, rows and the button.
    static func estimatedHeight(_ model: CutPastWorkoutsModel) -> CGFloat {
        let rows = model.workouts.map(\.exercises.count).max() ?? 0
        return 64 + 110 + CGFloat(rows) * 46 + 96
    }
}
