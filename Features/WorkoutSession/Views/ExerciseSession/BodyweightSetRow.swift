//  Set row component for bodyweight exercises (pull-ups, push-ups, etc.)
//  Shows only reps, no weight input
//

import SwiftUI

private typealias Theme = ExerciseSessionTheme

// MARK: - Bodyweight Set Row

struct BodyweightSetRow: View {
    let index: Int
    @Binding var set: SetInput
    let exercise: Exercise
    let isActive: Bool
    let isGhost: Bool
    let hasActiveTimer: Bool
    let onActivate: () -> Void
    let onLogSet: () -> Void

    @EnvironmentObject private var store: WorkoutStoreV2
    @ObservedObject private var timerManager = RestTimerManager.shared

    private let defaultWorkingReps = 10

    @State private var isEditingReps = false
    @FocusState private var focusedField: Field?

    enum Field {
        case reps
    }

    var body: some View {
        VStack(spacing: 0) {
            if set.isCompleted {
                completedRow
            } else {
                expandedRow
            }
        }
        .background(ChamferedRectangle(.large).fill(backgroundColor))
        .overlay(ChamferedRectangle(.large).stroke(borderColor, lineWidth: isActive ? 2 : 1))
        .opacity(rowOpacity)
        .animation(.easeInOut(duration: 0.2), value: isActive)
        .animation(.easeInOut(duration: 0.2), value: set.isCompleted)
        .animation(.easeInOut(duration: 0.2), value: hasActiveTimer)
        .onTapGesture {
            // Dismiss keyboard if editing, otherwise activate set
            if focusedField != nil {
                focusedField = nil
                isEditingReps = false
            } else if !set.isCompleted {
                set.isAutoGeneratedPlaceholder = false
                onActivate()
            }
        }
        .onChange(of: focusedField) { _, newValue in
            if newValue != .reps {
                isEditingReps = false
            }
        }
        .onAppear {
            seedFromMemoryIfNeeded()
        }
    }

    private var completedRow: some View {
        HStack(spacing: 8) {
            Image(systemName: "checkmark.circle.fill")
                .dsFont(.body, weight: .semibold)
                .foregroundStyle(Theme.accent)
                .frame(width: 22)

            Text("Set \(index)")
                .dsFont(.subheadline, weight: .semibold)
                .foregroundStyle(hasActiveTimer ? Theme.text.opacity(0.7) : Theme.secondary)
                .lineLimit(1)
                .fixedSize(horizontal: true, vertical: false)
                .layoutPriority(3)

            if hasActiveTimer && timerManager.isRunning {
                restTimerBadge
                    .layoutPriority(2)
            }

            Spacer(minLength: 8)

            Text("\(set.reps) reps")
                .dsFont(.subheadline, weight: .semibold, monospacedDigits: true)
                .foregroundStyle(Theme.text)
                .lineLimit(1)
                .layoutPriority(1)
        }
        .padding(.horizontal, 14)
        .padding(.vertical, 10)
        .frame(maxWidth: .infinity, minHeight: 56)
    }

    private var expandedRow: some View {
        VStack(spacing: 0) {
            headerRow

            Divider()
                .background(Theme.border)
                .padding(.horizontal, 16)

            repsEditor

            if isActive && !isGhost {
                Divider()
                    .background(Theme.border)
                    .padding(.horizontal, 16)

                Button(action: onLogSet) {
                    HStack(spacing: 8) {
                        Image(systemName: "checkmark.circle.fill")
                        Text("Log This Set")
                            .fontWeight(.semibold)
                    }
                    .dsFont(.subheadline)
                    .foregroundStyle(Color.black)
                    .frame(maxWidth: .infinity)
                    .frame(height: 44)
                    .background(Theme.accent)
                    .clipShape(RoundedRectangle(cornerRadius: 10, style: .continuous))
                }
                .buttonStyle(.plain)
                .padding(.horizontal, 16)
                .padding(.vertical, 8)
            }
        }
    }

    private var headerRow: some View {
        HStack(spacing: 12) {
            HStack(spacing: 6) {
                if isActive {
                    Circle()
                        .fill(Theme.accent)
                        .frame(width: 8, height: 8)
                } else {
                    Circle()
                        .strokeBorder(Theme.secondary.opacity(0.3), lineWidth: 1.5)
                        .frame(width: 8, height: 8)
                }

                Text("Set \(index)")
                    .dsFont(.subheadline, weight: isActive ? .bold : .semibold)
                    .foregroundStyle(Theme.text)
            }

            Spacer()

            TagDotCycler(tag: $set.tag)
                .disabled(isGhost)
        }
        .padding(.horizontal, 16)
        .padding(.top, 8)
        .padding(.bottom, 6)
    }

    private var repsEditor: some View {
        VStack(spacing: 8) {
            Text("REPS")
                .dsFont(.caption, weight: .semibold)
                .foregroundStyle(Theme.secondary)

            HStack(spacing: 12) {
                StepperButton(
                    systemName: "minus.circle.fill",
                    isEnabled: !isGhost && set.reps > 1,
                    color: Theme.accent.opacity(0.8)
                ) {
                    if set.reps > 1 {
                        set.reps -= 1
                        set.isAutoGeneratedPlaceholder = false
                        UIImpactFeedbackGenerator(style: .light).impactOccurred()
                    }
                }

                if isEditingReps {
                    TextField("", value: $set.reps, format: .number)
                        .keyboardType(.numberPad)
                        .focused($focusedField, equals: .reps)
                        .font(DS.Typography.custom(size: 52, weight: .bold))
                        .monospacedDigit()
                        .foregroundStyle(Theme.text)
                        .multilineTextAlignment(.center)
                        .frame(minWidth: 80)
                        .onChange(of: set.reps) { _, _ in
                            set.isAutoGeneratedPlaceholder = false
                        }
                } else {
                    Text("\(set.reps)")
                        .font(DS.Typography.custom(size: 52, weight: .bold))
                        .monospacedDigit()
                        .foregroundStyle(Theme.text)
                        .frame(minWidth: 80)
                        .contentShape(Rectangle())
                        .onTapGesture {
                            if !isGhost {
                                isEditingReps = true
                                focusedField = .reps
                            }
                        }
                }

                StepperButton(
                    systemName: "plus.circle.fill",
                    isEnabled: !isGhost,
                    color: Theme.accent
                ) {
                    set.reps += 1
                    set.isAutoGeneratedPlaceholder = false
                    UIImpactFeedbackGenerator(style: .light).impactOccurred()
                }
            }

            if let prReps = store.personalBestReps(for: exercise) {
                HStack(spacing: 12) {
                    if prReps > 0 {
                        Text("PR: \(prReps) reps")
                            .dsFont(.caption, weight: .medium)
                            .foregroundStyle(Theme.secondary)
                    }

                    if let last = store.lastWorkingSet(exercise: exercise), last.reps > 0 {
                        Text("•")
                            .dsFont(.caption2)
                            .foregroundStyle(Theme.secondary.opacity(0.5))
                        Text("Last: \(last.reps) reps")
                            .dsFont(.caption, weight: .medium)
                            .foregroundStyle(Theme.secondary)
                    }
                }
                .padding(.top, 4)
            }
        }
        .padding(.horizontal, 16)
        .padding(.vertical, 16)
    }

    private var restTimerBadge: some View {
        Button {
            timerManager.stopTimer()
            UIImpactFeedbackGenerator(style: .medium).impactOccurred()
        } label: {
            ViewThatFits(in: .horizontal) {
                restTimerBadgeContent(showsCancelText: true, horizontalPadding: 10)
                restTimerBadgeContent(showsCancelText: false, horizontalPadding: 8)
                restTimerBadgeContent(showsCancelText: false, horizontalPadding: 6)
            }
        }
        .buttonStyle(.plain)
    }

    private func restTimerBadgeContent(showsCancelText: Bool, horizontalPadding: CGFloat) -> some View {
        HStack(spacing: 4) {
            Image(systemName: "timer")
                .dsFont(.caption, weight: .medium)

            Text(formatTime(timerManager.remainingSeconds))
                .dsFont(.caption, weight: .semibold, monospacedDigits: true)

            if showsCancelText {
                Text("•")
                    .dsFont(.caption2)
                Text("Cancel")
                    .dsFont(.caption, weight: .semibold)
            }

            Image(systemName: "xmark.circle.fill")
                .dsFont(.caption)
        }
        .foregroundStyle(Theme.accent)
        .padding(.horizontal, horizontalPadding)
        .padding(.vertical, 5)
        .background(Theme.accent.opacity(0.15))
        .clipShape(Capsule())
        .overlay(Capsule().stroke(Theme.accent.opacity(0.3), lineWidth: 1))
        .lineLimit(1)
    }

    // MARK: - Styling

    private var backgroundColor: Color {
        if set.isCompleted && hasActiveTimer {
            return Theme.accent.opacity(0.08)
        } else if set.isCompleted {
            return Theme.accent.opacity(0.04)
        } else if isActive {
            return Theme.surface2
        } else {
            return Theme.surface
        }
    }

    private var borderColor: Color {
        if set.isCompleted && hasActiveTimer {
            return Theme.accent.opacity(0.5)
        } else if set.isCompleted {
            return Theme.accent.opacity(0.2)
        } else if isActive {
            return Theme.accent
        } else {
            return Theme.border
        }
    }

    private var rowOpacity: Double {
        if set.isCompleted && hasActiveTimer {
            return 0.85
        } else if set.isCompleted {
            return 0.65
        } else {
            return 1.0
        }
    }

    // MARK: - Helpers

    private func seedFromMemoryIfNeeded() {
        guard set.tag == .working, !set.didSeedFromMemory else { return }
        let looksEmpty = (set.reps == 0 && set.weight == 0)
        guard looksEmpty else { return }

        if let last = store.lastWorkingSet(exercise: exercise) {
            set.reps = last.reps
            set.weight = 0 // Always 0 for bodyweight
            set.didSeedFromMemory = true
            return
        }

        set.reps = (set.reps > 0) ? set.reps : defaultWorkingReps
        set.weight = 0
        set.didSeedFromMemory = true
    }

    private func formatTime(_ seconds: TimeInterval) -> String {
        let mins = Int(seconds) / 60
        let secs = Int(seconds) % 60
        return String(format: "%d:%02d", mins, secs)
    }
}

// MARK: - Stepper Button (Reused from SetRowViews)

private struct StepperButton: View {
    let systemName: String
    let isEnabled: Bool
    let color: Color
    let action: () -> Void

    @GestureState private var isPressingDown = false
    @State private var longPressTimer: Timer?

    var body: some View {
        Image(systemName: systemName)
            .dsFont(.title2)
            .foregroundStyle(isEnabled ? color : Theme.secondary.opacity(0.3))
            .frame(width: 44, height: 44)
            .contentShape(Rectangle())
            .gesture(
                DragGesture(minimumDistance: 0)
                    .updating($isPressingDown) { _, state, _ in
                        state = true
                    }
                    .onChanged { _ in
                        if isEnabled && longPressTimer == nil {
                            action()
                            UIImpactFeedbackGenerator(style: .light).impactOccurred()

                            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
                                if isPressingDown && isEnabled {
                                    startLongPress()
                                }
                            }
                        }
                    }
            )
            .onChange(of: isPressingDown) { _, pressing in
                if !pressing {
                    stopLongPress()
                }
            }
            .onDisappear { stopLongPress() }
    }

    private func startLongPress() {
        guard longPressTimer == nil else { return }
        UIImpactFeedbackGenerator(style: .medium).impactOccurred()

        longPressTimer = Timer.scheduledTimer(withTimeInterval: 0.1, repeats: true) { _ in
            if isEnabled {
                action()
            } else {
                stopLongPress()
            }
        }
    }

    private func stopLongPress() {
        longPressTimer?.invalidate()
        longPressTimer = nil
    }
}
